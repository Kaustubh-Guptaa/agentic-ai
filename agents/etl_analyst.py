from utils.llm_router import choose_llm
from utils.etl_tools import ETLTools
from models.schema import ETLAgentSchema
from langchain_core.messages import HumanMessage, ToolMessage
from langgraph.graph import StateGraph, START, END
from langchain.tools import tool # This acts as a decorator to define tools (utils) that can be used by the agent

# ---------------------------------- ETL Agent's Tools ----------------------------------

@tool
def extract_load_tool(url:str, output_folder:str, format:str) -> str:
    """
    This tool extracts the data from the API (url) and loads it into the
    the desired location (output_folder).

    Args:
        url (str): The API endpoint from which to extract data.
        output_folder (str): The folder where the extracted data will be saved.
        format (str): The format in which to save the extracted data (csv, json, parquet).
    
    Returns:
        str: A message indicating the success or failure of the operation.

    """
    etl_tools = ETLTools()
    return etl_tools.extract_data(url, output_folder, format)


@tool
def transform_load_tool(input_file_path:str, output_folder:str, output_format:str, user_question:str) -> str:
    """
    This tool transforms the data from the specified file and loads it into the
    desired location (output_folder).

    Args:
        input_file_path (str): The path to the file containing the data to be transformed.
        output_folder (str): The folder where the transformed data will be saved.
        output_format (str): The format in which to save the transformed data (csv, json, parquet).
    
    Returns:
        str: A message indicating the success or failure of the operation.

    """
    etl_tools = ETLTools()

    top_3_rows = etl_tools.transform_load_context(input_file_path)

    llm = choose_llm("medium")

    prompt = f"""
            You are a Python Data Analyst who uses Pandas to analyze data. 
            You need to provide only the Pandas Code that will help to perform the right ETL operations 
            on the data stored in the file: {input_file_path} as per the user's question. 
            Do not provide any explanation or comments, only the code should be provided. 
            The code should be in a format that can be executed in a Python environment with Pandas installed. 
            Don't write anything else than Pandas Code. \n
            
            Create the Pandas Dataframe from the data stored in the file : {input_file_path} and then 
            write the code to transform and save the data at {output_folder}.
            Here's the user's question: {user_question}\n
            Here's the context of the data you will be analyzing: {top_3_rows}\n

        """

    response = llm.invoke(prompt).content # Pandas code generated by the LLM based on the user's question and the context of the data

    # Execute the Pandas code
    results = etl_tools.execute_code(response)

    return f"The data is transformed and saved at {output_folder} in {output_format} format. \n\n Pandas Code Executed: \n {response} \n\n Execution Result: \n {results}"

# Toolkit 
tools = [extract_load_tool, transform_load_tool]


# ---------------------------------- ETL Agent -----------------------------

llm = choose_llm("function_tool") # Choose the LLM for the ETL agent
llm_bind = llm.bind_tools(tools) # Attach tools to the LLM so it can use them during the ETL process


def llm_node(state: ETLAgentSchema):
    """
    This function defines the behavior of the ETL agent. It takes the current state of the ETL process as input,
    generates a prompt for the LLM based on that state, and returns the LLM's response.

    Args:
        state (ETLAgentSchema): The current state of the ETL process.
    """
    
    messages = state.messages
    
    prompt = f"""
        You are a Python Data Analyst who has access to tools that can extract and load, 
        transform and load data. You will be provided with a user's question 
        and you would need to perform the right ETL operations as per the user's question. 
        If the operation is performed then inform the user and end the coversation.
        Here's the chat history: {messages} \n
    """
    
    response = llm_bind.invoke(prompt) # LLM's full response (keeps tool_calls, not just .content)
    state.messages.append(response) # Append the LLM's response to the chat history
    
    return state


def tool_node(state: ETLAgentSchema):
    """
    This node is responsible for invoking the appropriate tool 
    based on the user's question and the context provided by the LLM.
    """
    
    tools_results = []
    tools_by_name = {tool.name: tool for tool in tools} # tools is defined by the @tool decorator; a list of all the tools available to the agent
    tool_calls = state.messages[-1].tool_calls # Get the tool calls from the last message in the chat history

    for tool_call in tool_calls:
        tool = tools_by_name[tool_call['name']] # Get the tool by name
        observation = tool.invoke(tool_call['args']) # Invoke the tool with the provided arguments and get the observation (result)
        
        tools_results.append(ToolMessage(content=observation, tool_call_id = tool_call['id'])) # Append the tool's result to the tools_results list
        
    state.messages = state.messages + tools_results
    
    return state


# ---------------------------------- Graph Definition -----------------------------

# Nodes
etl_analyst_graph = StateGraph(ETLAgentSchema)
etl_analyst_graph.add_node("llm_node", llm_node)
etl_analyst_graph.add_node("tool_node", tool_node)

# Edges
etl_analyst_graph.add_edge(START, "llm_node")

def is_tool_call(state:ETLAgentSchema):
    tool_calls = state.messages[-1].tool_calls

    if tool_calls:
        return "tool_node"
    else:
        return "end"

etl_analyst_graph.add_conditional_edges(
    "llm_node", is_tool_call,
    {
        "tool_node": "tool_node",
        "end": END
    }
)

etl_analyst_graph.add_edge("tool_node", "llm_node")

etl_analyst = etl_analyst_graph.compile()

